class LBCAF_VQA(nn.Module):
    def __init__(
        self,
        vocab_size,
        d=512
    ):
        super().__init__()

        # Initialize the encoders
        self.image_encoder = ImageEncoder()
        self.text_encoder = TextEncoder()

        # LBCAF fusion module
        self.lbca = LBCAF(d=d)

        # Transformer-based answer decoder
        self.decoder = AnswerDecoder(
            txt_dim=1024,
            d=d,
            vocab_size=vocab_size
        )

    def forward(self, images, questions, answers=None):
        """
        images: (B, 3, 224, 224)
        questions: list[str]
        answers: (B, L) tokenized (for training)
        """

        # ---------------------------
        # 1. Encode the input images
        # ---------------------------
        F_out = self.image_encoder(images)   # (B, 196, 2048)

        # ---------------------------
        # 2. Encode the input questions
        # ---------------------------
        T = self.text_encoder(questions)     # (B, n, 1024)

        # ---------------------------
        # 3. Fuse image and text features using LBCAF
        # ---------------------------
        A_out = self.lbca(F_out, T)          # (B, d)

        # ---------------------------
        # 4. Generate the answer
        # ---------------------------
        if answers is not None:
            # Training mode (teacher forcing)
            logits = self.decoder(T, A_out, answers)
            return logits

        else:
            # Inference mode
            return A_out

