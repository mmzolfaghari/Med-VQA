class AnswerDecoder(nn.Module):
    def __init__(self, txt_dim=1024, d=512, vocab_size=30522):
        super().__init__()

        self.proj = nn.Linear(txt_dim + d, d)

        decoder_layer = nn.TransformerDecoderLayer(
            d_model=d,
            nhead=8,
            batch_first=True
        )

        self.decoder = nn.TransformerDecoder(decoder_layer, num_layers=2)

        self.embed = nn.Embedding(vocab_size, d)
        self.fc_out = nn.Linear(d, vocab_size)

    def forward(self, T, A_out, tgt_tokens):
        """
        T: (B, n, 1024)
        A_out: (B, d)
        tgt_tokens: (B, L)  <-- teacher forcing
        """

        B, n, _ = T.shape

        # multimodal memory
        A_expanded = A_out.unsqueeze(1).expand(-1, n, -1)
        memory = self.proj(torch.cat([T, A_expanded], dim=-1))  # (B, n, d)

        # target embeddings
        tgt_emb = self.embed(tgt_tokens)  # (B, L, d)

        # decoder
        out = self.decoder(tgt_emb, memory)  # (B, L, d)

        logits = self.fc_out(out)  # (B, L, vocab_size)

        return logits

