def generate(self, T, A_out, bos_id, eos_id, max_len=20):
    B = T.size(0)

    generated = torch.full((B, 1), bos_id).to(T.device)

    for _ in range(max_len):

        logits = self.forward(T, A_out, generated)
        next_token = logits[:, -1].argmax(dim=-1, keepdim=True)

        generated = torch.cat([generated, next_token], dim=1)

        if (next_token == eos_id).all():
            break

    return generated

