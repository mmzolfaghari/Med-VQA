import torchvision.models as models


class ImageEncoder(nn.Module):
    def __init__(self):
        super().__init__()

        resnet = models.resnet152(pretrained=True)

        # Remove the final fully connected layer and average pooling layer
        self.backbone = nn.Sequential(*list(resnet.children())[:-2])

        # As described in the paper: Adaptive Average Pooling to 14×14
        self.adaptive_pool = nn.AdaptiveAvgPool2d((14, 14))

    def forward(self, I):
        """
        I: (B, 3, 224, 224)
        """

        # F = ResNet152(I)
        F = self.backbone(I)  # (B, 2048, H, W)

        # Apply Adaptive Average Pooling → (B, 2048, 14, 14)
        F = self.adaptive_pool(F)

        B, C, H, W = F.shape  # H = W = 14

        # Reshape the feature map
        # Output shape: (B, 196, 2048)
        F_out = F.view(B, C, H * W).permute(0, 2, 1).contiguous()

        return F_out

