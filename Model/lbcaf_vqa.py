def generate(
    model,
    tokenizer,
    image,
    question,
    device,
    max_len=20,
    temperature=1.0,
    top_k=50
):
    """
    Autoregressive generation for LBCAF-VQA
    """

    model.eval()

    image = image.to(device)

    # =========================
    # Encode image + question (once)
    # =========================
    with torch.no_grad():
        # Get image features
        F_out = model.image_encoder(image)  # (B, 196, 2048)

        # Get question embeddings
        T = model.text_encoder(question)    # (B, n, 1024)

        # Fuse them to get A_out
        A_out = model.lbca(F_out, T)        # (B, d)

    # =========================
    # START TOKEN
    # =========================
    input_ids = torch.tensor(
        [[tokenizer.bos_token_id]],
        device=device
    )

    generated_token_ids = []

    # =========================
    # AUTOREGRESSIVE LOOP
    # =========================
    for _ in range(max_len):

        with torch.no_grad():
            # Use the AnswerDecoder to predict the next token
            # The decoder takes T, A_out, and the currently generated input_ids
            logits = model.decoder(T, A_out, input_ids) # (B, current_len, vocab_size)

            # We only care about the logits for the last generated token
            next_token_logits = logits[:, -1, :] # (B, vocab_size)

            # temperature scaling
            next_token_logits = next_token_logits / temperature

            # top-k filtering
            if top_k is not None:
                values, indices = torch.topk(next_token_logits, top_k)
                probs = torch.zeros_like(next_token_logits).scatter_(1, indices, F.softmax(values, dim=-1))
            else:
                probs = F.softmax(next_token_logits, dim=-1)

            # Sample the next token
            next_token = torch.multinomial(probs, num_samples=1) # (B, 1)

            # Append to input for next iteration
            input_ids = torch.cat([input_ids, next_token], dim=1)

            token_id = next_token.item()

            # EOS check
            if token_id == tokenizer.eos_token_id:
                break

            generated_token_ids.append(token_id)

    # =========================
    # DECODE OUTPUT
    # =========================
    text = tokenizer.decode(generated_token_ids, skip_special_tokens=True)

    return text

