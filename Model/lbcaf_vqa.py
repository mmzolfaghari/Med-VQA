def fusion_module(V, Q, mode="lbcaf"):

    if mode == "concat":
        return torch.cat([V, Q], dim=-1)

    elif mode == "sum":
        return V + Q

    elif mode == "hadamard":
        return V * Q

    elif mode == "attention":
        attn = torch.softmax(torch.matmul(Q, V.transpose(-1, -2)), dim=-1)
        return torch.matmul(attn, V)

    elif mode == "lbcaf":
        # your full method
        S = torch.matmul(Q, V.transpose(-1, -2))
        A = torch.softmax(S, dim=-1)
        V_att = torch.matmul(A, V)
        return V_att + Q

    else:
        raise ValueError("Unknown fusion mode")

